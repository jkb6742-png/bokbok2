function ctxOf(text, i, len, pad = 18) {
  const a = Math.max(0, i - pad), b = Math.min(text.length, i + len + pad);
  return (a > 0 ? '…' : '') + text.slice(a, b).replace(/\s+/g, ' ') + (b < text.length ? '…' : '');
}

function check(text, { title = '', dept = null, maxPerRule = 5 } = {}) {
  const body = String(text || '');
  const full = (title ? title + '\n' : '') + body;
  const hits = [];
  for (const r of RULES) {
    if (!r.re || (r.depts && dept && !r.depts.includes(dept))) continue;
    const re = new RegExp(r.re.source, r.re.flags.includes('g') ? r.re.flags : r.re.flags + 'g');
    let m, n = 0;
    while ((m = re.exec(full)) && n < maxPerRule) {
      if (!m[0]) { re.lastIndex++; continue; }
      if (r.neg && NEG_AFTER.test(full.slice(m.index + m[0].length, m.index + m[0].length + 22))) continue;
      hits.push({ id: r.id, name: r.name, level: r.level, law: r.law, match: m[0].trim(), at: m.index, inTitle: !!title && m.index < title.length, context: ctxOf(full, m.index, m[0].length), fix: r.fix });
      n++;
    }
  }
  for (const [id, test] of Object.entries(DOC)) if (test(full)) { const r = RULES.find(x => x.id === id); hits.push({ id, name: r.name, level: r.level, law: r.law, match: '', at: -1, context: '글 전체', fix: r.fix }); }
  const counts = { block: 0, warn: 0, note: 0 };
  hits.forEach(h => counts[h.level]++);
  const level = counts.block ? 'block' : counts.warn ? 'warn' : counts.note ? 'note' : 'ok';
  const summary = level === 'ok' ? '걸리는 표현이 없습니다' : `차단 ${counts.block} · 경고 ${counts.warn} · 주의 ${counts.note}`;
  return { level, label: LABEL[level] || '통과', counts, hits: hits.sort((a, b) => LV[b.level] - LV[a.level] || a.at - b.at), summary, version: VERSION };
}
const rules = () => RULES.map(r => ({ id: r.id, name: r.name, level: r.level, label: LABEL[r.level], law: r.law, fix: r.fix, how: r.manual ? '사람 확인' : r.doc ? '글 전체 판단' : '문구 탐지', pattern: r.re ? r.re.source : null }));

module.exports = { check, rules, RULES, LABEL, VERSION };
